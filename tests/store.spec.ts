import { test, expect } from '@playwright/test';
test('fluxo equivalente e fronteiras de carregamento',async({page,baseURL},info)=>{
 const requests:string[]=[];const errors:string[]=[];
 page.on('request',r=>requests.push(r.url()));page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await expect(page.locator('.card')).toHaveCount(32);
 const lazy=['images','combined'].includes(info.project.name);
 await expect(page.locator('.card img').first()).toHaveAttribute('loading',lazy?'lazy':'eager');
 expect(requests.some(u=>/Compare-.*\.js/.test(u))).toBe(false);
 if(['routes','combined'].includes(info.project.name))expect(requests.some(u=>/Checkout-.*\.js/.test(u))).toBe(false);
 await page.getByLabel('Buscar produto').fill('Vaso Aurora');await expect(page.locator('.card')).toHaveCount(1);
 await page.getByLabel('Buscar produto').fill('');
 await page.getByLabel('Comparar produto',{exact:true}).nth(0).check();await page.getByLabel('Comparar produto',{exact:true}).nth(1).check();
 await page.getByRole('button',{name:'Comparar (2/3)',exact:true}).click();await expect(page.getByRole('dialog')).toBeVisible();
 expect(requests.some(u=>/Compare-.*\.js/.test(u))).toBe(['interaction','combined'].includes(info.project.name));
 await page.getByRole('button',{name:'Fechar',exact:true}).click();
 await page.locator('.card a[href="/produto/p01"]').click();
 await expect(page.getByRole('heading',{name:'Vaso Aurora'})).toBeVisible();
 await page.getByRole('button',{name:'Adicionar à sacola'}).click();await page.getByRole('link',{name:'Ver sacola'}).click();
 await page.getByLabel('Quantidade de Vaso Aurora').fill('2');await expect(page.getByRole('heading',{name:'Total: R$ 258,00'})).toBeVisible();
 await page.getByRole('link',{name:'Continuar para checkout'}).click();
 await page.getByLabel('Nome fictício').fill('Pessoa Teste');await page.getByLabel('E-mail fictício').fill('teste@example.invalid');await page.getByLabel('Endereço fictício').fill('Rua fictícia, 123');
 await page.getByRole('button',{name:'Concluir pedido simulado'}).click();await expect(page.getByRole('heading',{name:'Pedido simulado concluído'})).toBeVisible();
 await expect(page.getByRole('link',{name:'Sacola (0)'})).toBeVisible();
 expect(errors).toEqual([]);expect(requests.every(u=>u.startsWith(baseURL!))).toBe(true);
 await page.goto('/produto/inexistente');await expect(page.getByRole('heading',{name:'Produto não encontrado'})).toBeVisible();
 await page.goto('/checkout');await expect(page.getByRole('heading',{name:'Sua sacola está vazia'})).toBeVisible();
});
